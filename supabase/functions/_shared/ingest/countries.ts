/** Maps alpha-3 codes to alpha-2, dropping unknown ones and duplicates. */
export function toAlpha2(
  codes: readonly string[] | null | undefined,
): string[] {
  const out = new Set<string>();
  for (const code of codes ?? []) {
    const alpha2 = ALPHA3_TO_ALPHA2[code.trim().toUpperCase()];
    if (alpha2) out.add(alpha2);
  }
  return [...out].sort();
}

/** Location wording that means "no country restriction". */
const UNRESTRICTED = /\b(world ?wide|global|anywhere|international)\b/;

/** Names sources use that differ from the English names Intl gives. */
const NAME_ALIASES: Readonly<Record<string, string>> = {
  "united states of america": "US",
  usa: "US",
  us: "US",
  "u.s.": "US",
  uk: "GB",
  "great britain": "GB",
  england: "GB",
  scotland: "GB",
  wales: "GB",
  turkey: "TR",
  "hong kong": "HK",
  macau: "MO",
  "czech republic": "CZ",
  "south korea": "KR",
  korea: "KR",
  "ivory coast": "CI",
  "democratic republic of the congo": "CD",
  "republic of the congo": "CG",
  "the netherlands": "NL",
  holland: "NL",
  uae: "AE",
};

function normalizeName(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/\s+/g, " ")
    .trim();
}

let nameIndex: Map<string, string> | undefined;

/** English country name → alpha-2, built once from Intl's region names. */
function nameToAlpha2(): Map<string, string> {
  if (nameIndex) return nameIndex;
  const names = new Intl.DisplayNames(["en"], { type: "region" });
  nameIndex = new Map();
  for (const code of new Set(Object.values(ALPHA3_TO_ALPHA2))) {
    const name = names.of(code);
    if (name && name !== code) nameIndex.set(normalizeName(name), code);
  }
  for (const [alias, code] of Object.entries(NAME_ALIASES)) {
    nameIndex.set(alias, code);
  }
  return nameIndex;
}

/**
 * Countries a free-text location names ("United States of America",
 * "Remote US", "Spain; Portugal", "Mexico City, Mexico"). Empty when the
 * location is worldwide or nothing is recognised, which the feed treats
 * as open to everyone.
 */
export function countriesFromLocation(
  location: string | null | undefined,
): string[] {
  const index = nameToAlpha2();
  const out = new Set<string>();
  for (const part of (location ?? "").split(/[;|/]/)) {
    const words = normalizeName(
      part.replace(/\(.*?\)/g, " ").replace(/[-–—]+/g, " "),
    );
    if (UNRESTRICTED.test(words)) return [];
    const cleaned = normalizeName(
      words.replace(/\b(remote|hybrid|on ?site|only|based)\b/g, " "),
    );
    // A bare "Remote" names no country: open to everyone.
    if (cleaned === "") return [];
    const segments = cleaned.split(",").map((segment) => segment.trim());
    const code =
      index.get(cleaned) ??
      index.get(segments[segments.length - 1] ?? "") ??
      undefined;
    if (code) out.add(code);
  }
  return [...out].sort();
}
